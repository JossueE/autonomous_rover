constexpr double kDefaultConcaveAlpha = 0.15;

// ANSI color escape codes used by ROS log messages.
constexpr const char *kGreen = "\033[1;32m";
constexpr const char *kRed = "\033[1;31m";
constexpr const char *kYellow = "\033[1;33m";
constexpr const char *kBlue = "\033[1;34m";
constexpr const char *kReset = "\033[0m";

/**
 * @brief Normalize hull mode names for parameter validation.
 *
 * Converts the configured HULL_MODE string to lowercase so values like
 * "Convex", "CONVEX", or "convex" are handled consistently.
 *
 * @param mode Hull mode string read from ROS parameters.
 * @return Lowercase hull mode string.
 */
std::string normalizeHullMode(std::string mode)
{
    std::transform(mode.begin(), mode.end(), mode.begin(),
                   [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    return mode;
}

Eigen::Matrix4f transformToMatrix(const geometry_msgs::msg::TransformStamped &transform)
{
    const auto &translation = transform.transform.translation;
    const auto &rotation = transform.transform.rotation;

    tf2::Quaternion quaternion(rotation.x, rotation.y, rotation.z, rotation.w);
    tf2::Matrix3x3 rotation_matrix(quaternion);

    Eigen::Matrix4f matrix = Eigen::Matrix4f::Identity();
    for (int row = 0; row < 3; ++row)
    {
        for (int col = 0; col < 3; ++col)
        {
            matrix(row, col) = static_cast<float>(rotation_matrix[row][col]);
        }
    }
    matrix(0, 3) = static_cast<float>(translation.x);
    matrix(1, 3) = static_cast<float>(translation.y);
    matrix(2, 3) = static_cast<float>(translation.z);
    return matrix;
}

/**
 * @brief Convert a PCL hull point cloud into a closed ROS polygon.
 *
 * Copies each hull vertex into a geometry_msgs polygon and repeats the first
 * point at the end so downstream consumers receive a closed obstacle boundary.
 *
 * @param hull_cloud Hull point cloud generated by PCL.
 * @param polygon Output polygon message.
 * @return true when the hull has enough vertices to form a polygon.
 * @note A valid polygon needs at least three vertices.
 */
bool buildClosedPolygonFromHull(const pcl::PointCloud<pcl::PointXYZ>::Ptr &hull_cloud,
                                geometry_msgs::msg::Polygon &polygon)
{
    if (!hull_cloud || hull_cloud->points.size() < 3)
    {
        return false;
    }

    polygon.points.clear();
    polygon.points.reserve(hull_cloud->points.size() + 1);
    for (const auto &point : hull_cloud->points)
    {
        geometry_msgs::msg::Point32 p;
        p.x = point.x;
        p.y = point.y;
        p.z = 0.0;
        polygon.points.push_back(p);
    }

    polygon.points.push_back(polygon.points.front());
    return true;
}
